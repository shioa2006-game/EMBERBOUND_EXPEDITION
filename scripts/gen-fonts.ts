// Generates src/styles/fonts.css from the installed @fontsource packages, keeping only the woff2
// sources (every browser that runs this game supports woff2). The single-file build inlines every
// referenced font file, so dropping the .woff fallbacks roughly halves the bundle.
// Usage: node scripts/gen-fonts.ts
import { readFileSync, writeFileSync } from 'node:fs';

const SHEETS = ['dotgothic16/400.css', 'pixelify-sans/400.css', 'pixelify-sans/700.css', 'silkscreen/400.css'];
let out = '/* Generated by scripts/gen-fonts.ts — woff2-only copies of the @fontsource stylesheets. */\n';
for (const sheet of SHEETS) {
  const pkg = sheet.split('/')[0];
  const css = readFileSync(`node_modules/@fontsource/${sheet}`, 'utf8');
  out += css
    .replace(/, url\(\.\/files\/[^)]+\.woff\) format\('woff'\)/g, '')
    .replace(/url\(\.\/files\//g, `url(../../node_modules/@fontsource/${pkg}/files/`);
  out += '\n';
}
writeFileSync('src/styles/fonts.css', out);
console.log(`wrote src/styles/fonts.css (${out.length} chars)`);

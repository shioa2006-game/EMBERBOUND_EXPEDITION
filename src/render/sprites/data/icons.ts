// 16x16 icon art: ASCII maps (≤ 14x14 content; the outline brings them to 16x16) + palettes.
import type { Palette } from '../pix.ts';
import { cc } from './draw.ts';

export interface IconArt {
  rows: readonly string[];
  pal: Palette;
  /** Chars painted after the outline (no dark border). */
  glow?: string;
  out?: string;
}

const GOLD: Palette = { Y: '#fff2a0', y: '#ffd84a', o: '#e09a2a', d: '#9a5a1a', W: '#ffffff' };
const FIRE: Palette = { W: '#fffbe0', Y: '#fff2a0', y: '#ffd27a', o: '#ff9a3a', r: '#ff5a1e', d: '#b8301a' };

function coin(): string[] {
  const c = cc(14, 14);
  c.blob(6.5, 6.5, 6.2, 6.2, 'Yyyo').blob(6.5, 6.8, 6.2, 6.2, 'o', 0, 0, true);
  c.radial(6.5, 6.5, 4.3, 4.3, 'yyyyYo').rim('yYo', 'o', 0, 1);
  c.stamp(['.d.', 'ddd', '.d.', '.d.'], 5, 4).stamp(['W'], 3, 3).stamp(['W'], 4, 2);
  return c.out();
}

